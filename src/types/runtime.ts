/**
 * Canonical Python R1 ActionEnvelope schema specification.
 * Corresponds to snake_case schema defined in Python R1 machine runtime.
 * NOTE: The frontend demonstration does NOT claim to satisfy this schema directly;
 * an adapter mapping layer is required when connecting to the live Python gateway.
 */
export interface R1ActionEnvelope {
  header: {
    schema_version: 'r1.w00';
    timestamp_utc: string;
    correlation_id: string;
  };
  action_id: string;
  source_kind: 'CLIENT_UI' | 'AI_DIRECTOR' | 'SYSTEM_WORKER';
  source_ref: string;
  actor_refs: string[];
  action_type: string;
  arguments: Record<string, unknown>;
  authority_mode: 'FULL_AI' | 'CO_DM_AI_PRIMARY' | 'CO_DM_HUMAN_PRIMARY' | 'HUMAN_DM_ASSIST' | 'HUMAN_SOVEREIGN';
  input_hash: string;
}

/**
 * Canonical Python R1 CommitReceipt schema specification.
 */
export interface R1CommitReceipt {
  commit_seq: number;
  commit_hash: string;
  status: 'APPLIED' | 'NOOP_DUPLICATE_REPLAY' | 'REJECTED_STALE' | 'REJECTED_PERMISSION_DENIED' | 'REJECTED_INVARIANT_VIOLATION';
  committed_at_utc: string;
  state_hash_after: string;
  causal_event_refs: string[];
  error_detail?: string;
}

