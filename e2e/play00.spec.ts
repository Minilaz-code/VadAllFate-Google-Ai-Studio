import {test,expect} from '@playwright/test';
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';

test('PLAY-00 connected original legacy application journey',async({page})=>{
  test.setTimeout(300000);page.setDefaultTimeout(20000);
  test.skip(!process.env.VADALLFATE_PLAY00_CONTROL,'Explicit original disposable PLAY-00 runtime required');
  const control=JSON.parse(readFileSync(process.env.VADALLFATE_PLAY00_CONTROL!,'utf8'));
  const host=JSON.parse(readFileSync(join(control.root,'launcher','pids.json'),'utf8'));
  const failures:any[]=[];page.on('response',r=>{if(r.status()>=400){failures.push({path:new URL(r.url()).pathname,status:r.status()});writeFileSync(join(control.root,'http-failures.private.json'),JSON.stringify(failures));console.log('PLAY00_HTTP_FAILURE',new URL(r.url()).pathname,r.status());}});
  await page.goto('/');
  await page.getByLabel('Host bootstrap key').fill(host.hostKey);
  await page.getByRole('button',{name:'Authenticate',exact:true}).click();
  await expect(page.getByLabel('Authoritative dice')).toBeVisible();
  const source=page.getByRole('region',{name:'Campaign source content'});
  await source.getByRole('button',{name:/Campaign content/}).click();
  await source.getByText('Campaigns and Save branches',{exact:true}).click();
  await source.getByLabel('New campaign name').fill('PLAY-00 Original Lantern Journey');
  await source.getByRole('button',{name:'Create campaign',exact:true}).click();
  await expect(source.getByRole('status')).toContainText('Campaign session changed');
  await source.getByLabel('World pack').selectOption({label:'example.reliability · 1.0.0'});
  await source.getByLabel('Adventure pack').selectOption({label:'example.lost-bell · 1.0.0'});
  await source.getByRole('button',{name:'Pin selected content',exact:true}).click();
  await source.getByText('Prepare a connected noncombat adventure · DM only',{exact:true}).click();
  for(const [label,value] of [['Adventure host','example.lantern-marsh:keeper'],['Appointment contact','example.reliability:observer'],['Adventure start location','example.lantern-marsh:landing'],['Appointment location','example.reliability:tower'],['Adventure source scene','example.lost-bell:pier']])await source.getByLabel(label,{exact:true}).selectOption(value);
  await source.getByText('Approve these identities, draft instances and the appointment conditions for this campaign',{exact:true}).click();
  await source.getByRole('button',{name:'Prepare adventure',exact:true}).click();
  await expect(page.getByRole('region',{name:'Adventure play'})).toBeVisible();
  await page.getByLabel('Authoritative dice').locator('summary').click();
  await page.getByRole('button',{name:'Require DM confirmation of physical rolls',exact:true}).click();
  await expect(page.getByLabel('Authoritative dice')).toContainText('REQUIRE_DM_CONFIRMATION');
  await page.getByLabel('Roll character').selectOption('char-lyra-01');
  await page.getByLabel('Adjudicated HP').fill('24');
  await page.getByLabel('HP adjudication reason').fill('Original lantern mishap, manually adjudicated by the DM.');
  await page.getByRole('button',{name:'Record DM HP',exact:true}).click();
  await expect(page.getByLabel('Authoritative dice').getByRole('status')).toContainText('committed');
  await page.getByLabel('Select Role and Hosting Status').click();
  await page.getByRole('button',{name:'Player Guest: Lyra',exact:false}).click();
  const play=page.getByRole('region',{name:'Adventure play'});
  await play.getByRole('button',{name:'Enter Reed Landing',exact:true}).click();
  await expect(play.getByLabel('People present')).toContainText('Nera Reed');
  const aiStatuses:string[]=[]; const recallDemonstrated=false;
  const rolls=page.getByLabel('Authoritative dice');
  await expect(rolls.getByRole('button',{name:'Request d20 check',exact:true})).toBeEnabled();
  await rolls.getByRole('button',{name:'Request d20 check',exact:true}).click();
  const physical=rolls.locator('article').last();
  await expect(physical).toContainText('PENDING_INPUT');
  const requestId=(await physical.getAttribute('aria-label'))!.slice(5);
  await physical.getByLabel('Physical faces '+requestId).fill('14');
  await physical.getByRole('button',{name:'Report physical roll',exact:true}).click();
  await expect(physical).toContainText('PENDING_CONFIRMATION');
  await page.getByLabel('Select Role and Hosting Status').click();
  await page.getByRole('button',{name:'Dungeon Master (Host)',exact:false}).click();
  await rolls.getByRole('button',{name:'Confirm physical roll',exact:true}).click();
  await expect(physical).toContainText('Confirmed result: 14');
  await page.getByLabel('Select Role and Hosting Status').click();
  await page.getByRole('button',{name:'Player Guest: Lyra',exact:false}).click();
  await expect(rolls.getByRole('button',{name:'Request d20 check',exact:true})).toBeEnabled();
  await rolls.getByRole('button',{name:'Request d20 check',exact:true}).click();
  await rolls.locator('article').last().getByRole('button',{name:'Roll digitally',exact:true}).click();
  await expect(rolls.locator('article').last()).toContainText('SERVER_GENERATED');
  await page.getByRole('button',{name:'Character',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Lyra Vance',exact:true})).toBeVisible();
  await page.getByRole('button',{name:/Inventory/}).click();
  const item=page.locator('div.p-3').filter({has:page.getByText('Potion of Healing',{exact:true})}).last();
  await item.getByRole('button',{name:'Use',exact:true}).click();
  await expect(page.getByText(/one potion consumed/)).toBeVisible();
  await expect(item).toContainText('Qty: 1');
  await page.screenshot({path:join(control.root,'play00-character.png'),fullPage:true});
  const evidence=await page.evaluate(async(api)=>{
    const sessions=JSON.parse(sessionStorage.getItem('vadallfate.v2.session')!);
    const headers={'X-VadAllFate-Session-Token':sessions.player};
    const p=await fetch(api+'/projection?campaign_id='+encodeURIComponent(sessions.campaignId),{headers});
    if(!p.ok)throw new Error('Projection verification HTTP '+p.status);
    const projection=await p.json();
    const status=await (await fetch(api+'/status?campaign_id='+encodeURIComponent(sessions.campaignId),{headers})).json();
    const lyra=projection.characters.find((c:any)=>c.id===projection.activeCharacterId);
    return {snapshot:{commitSequence:status.commitSequence,stateHash:status.fullStateHash||status.stateHash,worldMinute:status.worldMinute},campaignId:projection.campaignId,worldClock:projection.worldClock,
      hp:lyra.currentHp,inventory:lyra.inventory.map((i:any)=>({id:i.id,quantity:i.quantity})),rolls:projection.activeRollRequests};
  },'http://127.0.0.1:'+control.api+'/api/v2');
  expect(evidence.hp).toBeGreaterThan(24);
  writeFileSync(join(control.root,'journey.private.json'),JSON.stringify({...evidence,aiStatuses,recallDemonstrated}));
  await page.getByRole('button',{name:'Play',exact:true}).click();
  await page.screenshot({path:join(control.root,'play00-initial.png'),fullPage:true});
  writeFileSync(join(control.root,'play00-ui.private.txt'),await page.locator('body').ariaSnapshot());
});
